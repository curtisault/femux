//! The built-in plugin registry (REQ-PLUG-001): every plugin compiled in by its feature, then
//! filtered by `[plugins] enabled` at runtime.
use femux_plugin::Plugin;

/// Every plugin compiled into this binary.
#[allow(clippy::vec_init_then_push)]
pub fn compiled() -> Vec<Plugin> {
    let mut out: Vec<Plugin> = Vec::new();
    #[cfg(feature = "agents")]
    out.push(femux_plugin_agents::plugin());
    #[cfg(feature = "infobar")]
    out.push(femux_plugin_infobar::plugin());
    #[cfg(feature = "notify")]
    out.push(femux_plugin_notify::plugin());
    #[cfg(feature = "git")]
    out.push(femux_plugin_git::plugin());
    #[cfg(feature = "clipboard")]
    out.push(femux_plugin_clipboard::plugin());
    #[cfg(feature = "graphics")]
    out.push(femux_plugin_graphics::plugin());
    #[cfg(feature = "shell-integration")]
    out.push(femux_plugin_shell_integration::plugin());
    #[cfg(feature = "broadcast")]
    out.push(femux_plugin_broadcast::plugin());
    #[cfg(feature = "which-key")]
    out.push(femux_plugin_which_key::plugin());
    #[cfg(feature = "recorder")]
    out.push(femux_plugin_recorder::plugin());
    #[cfg(feature = "hosts")]
    out.push(femux_plugin_hosts::plugin());
    #[cfg(feature = "theme")]
    out.push(femux_plugin_theme::plugin());
    #[cfg(feature = "launcher")]
    out.push(femux_plugin_launcher::plugin());
    out
}

/// The compiled plugins named in `enabled`, in registry order.
pub fn enabled(enabled: &[String]) -> Vec<Plugin> {
    compiled()
        .into_iter()
        .filter(|p| enabled.iter().any(|e| e == p.name))
        .collect()
}

#[cfg(test)]
mod tests {
    use femux_client::bindings::{Action, Bindings};
    use femux_client::config::ClientConfig;
    use femux_client::keys::Chord;
    use femux_plugin::Table;

    const DOC: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/prefixes.md");
    const BEGIN: &str = "<!-- BEGIN generated by `UPDATE_DOCS=1 mise exec -- cargo test -p femux-cli prefixes_doc`; do not edit by hand -->";
    const END: &str = "<!-- END generated -->";

    /// One table row: the chords, and the action and plugin they share.
    struct Row {
        keys: Vec<Chord>,
        action: Action,
        plugin: Option<&'static str>,
    }

    fn parameterized(a: Action) -> bool {
        matches!(
            a,
            Action::Focus(_) | Action::Resize(_) | Action::Preselect(_) | Action::Tab(_)
        )
    }

    /// Chords for the same action share a row, as do adjacent ones of a family (`h j k l`, `1-9`).
    fn rows(
        list: &[(Chord, Action)],
        plugin_of: impl Fn(&Chord) -> Option<&'static str>,
    ) -> Vec<Row> {
        let mut out: Vec<Row> = Vec::new();
        for (c, a) in list {
            let plugin = plugin_of(c);
            if let Some(same) = out
                .iter_mut()
                .find(|r| r.action == *a && r.plugin == plugin)
            {
                same.keys.push(c.clone());
                continue;
            }
            if let Some(last) = out.last_mut()
                && last.plugin == plugin
                && parameterized(*a)
                && std::mem::discriminant(&last.action) == std::mem::discriminant(a)
            {
                last.keys.push(c.clone());
                continue;
            }
            out.push(Row {
                keys: vec![c.clone()],
                action: *a,
                plugin,
            });
        }
        out
    }

    fn cell_keys(keys: &[Chord]) -> String {
        if keys.len() == 9 && keys.iter().all(|k| k.key.len() == 1) && keys[0].key == "1" {
            return "`1`-`9`".into();
        }
        keys.iter()
            .map(|k| format!("`{}`", k.to_string().replace('|', "\\|")))
            .collect::<Vec<_>>()
            .join(" ")
    }

    fn cell_action(r: &Row) -> String {
        let name = r.action.name();
        if r.keys.len() > 1 && parameterized(r.action) {
            let (head, _) = name.rsplit_once(' ').unwrap();
            let what = if matches!(r.action, Action::Tab(_)) {
                "n"
            } else {
                "direction"
            };
            return format!("`{head} <{what}>`");
        }
        format!("`{name}`")
    }

    fn cell_does(r: &Row, enabled: &[String]) -> String {
        let mut d = if r.keys.len() > 1 && parameterized(r.action) {
            match r.action {
                Action::Focus(_) => "focus the pane in that direction".into(),
                Action::Resize(_) => "grow the pane in that direction".into(),
                Action::Preselect(_) => "put the next split on that side".into(),
                _ => "select that tab".into(),
            }
        } else {
            r.action.describe()
        };
        if let Some(p) = r.plugin {
            let off = if enabled.iter().any(|e| e == p) {
                ""
            } else {
                ", off by default"
            };
            d.push_str(&format!(" (`{p}` plugin{off})"));
        }
        d
    }

    fn table(out: &mut String, rows: &[Row], enabled: &[String]) {
        out.push_str("| key | action | what it does |\n| --- | --- | --- |\n");
        for r in rows {
            out.push_str(&format!(
                "| {} | {} | {} |\n",
                cell_keys(&r.keys),
                cell_action(r),
                cell_does(r, enabled)
            ));
        }
    }

    /// The generated part of `docs/prefixes.md`: the default tables plus every compiled-in
    /// plugin's keys, grouped as the which-key panel groups them.
    fn render() -> String {
        let defaults = Bindings::from_config(&ClientConfig::default());
        let mut b = defaults.clone();
        let mut owner: Vec<(Table, Chord, &'static str)> = Vec::new();
        for p in super::compiled() {
            if let Some(c) = &p.client {
                let bs = c.bindings();
                b.add_plugin(&bs);
                for x in &bs {
                    if let Some(ch) = Chord::parse(&x.key) {
                        owner.push((x.table, ch, p.name));
                    }
                }
            }
        }
        let enabled = femux_config::Config::default().plugins.enabled;
        let plugin_of = |t: Table| {
            let owner = &owner;
            move |c: &Chord| {
                owner
                    .iter()
                    .find(|(ot, oc, _)| *ot == t && oc == c)
                    .map(|(_, _, n)| *n)
            }
        };

        let mut out = String::new();
        out.push_str(BEGIN);
        out.push_str("\n\n## Root table\n\n");
        if b.root.is_empty() {
            out.push_str("Nothing is bound without the prefix.\n");
        } else {
            table(&mut out, &rows(&b.root, plugin_of(Table::Root)), &enabled);
        }
        out.push_str("\n## Prefix table\n\nPress the prefix, then the key.\n");
        let prefix = rows(&b.prefix, plugin_of(Table::Prefix));
        let mut groups: Vec<&str> = Vec::new();
        for r in &prefix {
            if !groups.contains(&r.action.group()) {
                groups.push(r.action.group());
            }
        }
        for g in groups {
            out.push_str(&format!("\n### {g}\n\n"));
            let in_group: Vec<Row> = prefix
                .iter()
                .filter(|r| r.action.group() == g)
                .map(|r| Row {
                    keys: r.keys.clone(),
                    action: r.action,
                    plugin: r.plugin,
                })
                .collect();
            table(&mut out, &in_group, &enabled);
        }
        out.push_str("\n## Copy mode\n\n");
        table(&mut out, &rows(&b.copy, plugin_of(Table::Copy)), &enabled);
        out.push('\n');
        out.push_str(END);
        out
    }

    #[test]
    fn prefixes_doc_matches_the_default_bindings() {
        let text = std::fs::read_to_string(DOC).expect("docs/prefixes.md");
        let (head, rest) = text.split_once(BEGIN).expect("BEGIN marker");
        let (_, tail) = rest.split_once(END).expect("END marker");
        let want = format!("{head}{}{tail}", render());
        if std::env::var_os("UPDATE_DOCS").is_some() {
            std::fs::write(DOC, &want).unwrap();
            return;
        }
        assert!(
            text == want,
            "docs/prefixes.md is out of date with the default bindings; rerun with UPDATE_DOCS=1"
        );
    }
}
